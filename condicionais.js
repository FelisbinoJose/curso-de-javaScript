// Entre 9 e 10: Excelente
// Entre 7 e 8: Bom
// Entre 4 e 6: Médio
// Entre 0 e 3: Ruim

const notaDoAluno = 4;

if (notaDoAluno >= 9) {
    console.log("Excelente");
} else if (notaDoAluno >= 7) {
    console.log("Bom");
} else if (notaDoAluno >= 4) {
    console.log("Médio");
} else {
    console.log("Ruim");
}
